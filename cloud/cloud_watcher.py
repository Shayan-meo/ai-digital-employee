"""
Cloud Watcher - Platinum Tier
24/7 always-on watcher for Cloud VM

Responsibilities:
- Monitor Gmail for new emails (draft replies only)
- Monitor social media for engagement (draft posts only)
- Create draft files in /Pending_Approval/
- Write updates to /Updates/ for Local agent
- NEVER send emails or post directly (draft-only)

Usage:
    python cloud_watcher.py
"""

import logging
import time
import json
from pathlib import Path
from datetime import datetime
from abc import ABC, abstractmethod

# Vault paths
VAULT_ROOT = Path(__file__).parent.resolve()
NEEDS_ACTION = VAULT_ROOT / "Needs_Action"
PENDING_APPROVAL = VAULT_ROOT / "Pending_Approval"
UPDATES = VAULT_ROOT / "Updates"
IN_PROGRESS = VAULT_ROOT / "In_Progress" / "cloud"
LOGS = VAULT_ROOT / "Logs"

# Ensure directories exist
for d in [NEEDS_ACTION, PENDING_APPROVAL, UPDATES, IN_PROGRESS, LOGS]:
    d.mkdir(parents=True, exist_ok=True)

# Configure logging
log_file = LOGS / f"cloud_watcher_{datetime.now():%Y-%m-%d}.log"
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
    handlers=[
        logging.FileHandler(log_file, encoding="utf-8"),
        logging.StreamHandler(),
    ],
)
logger = logging.getLogger(__name__)


class BaseCloudWatcher(ABC):
    """Base class for all cloud watchers."""
    
    def __init__(self, check_interval: int = 60):
        self.check_interval = check_interval
        self.processed_ids = set()
        self.state_file = VAULT_ROOT / f".{self.__class__.__name__}_state.json"
        self.load_state()
    
    def load_state(self):
        """Load processed IDs from state file."""
        if self.state_file.exists():
            try:
                data = json.loads(self.state_file.read_text(encoding="utf-8"))
                self.processed_ids = set(data.get("processed_ids", []))
            except (json.JSONDecodeError, OSError):
                pass
    
    def save_state(self):
        """Save processed IDs to state file."""
        data = {"processed_ids": list(self.processed_ids)}
        self.state_file.write_text(json.dumps(data, indent=2), encoding="utf-8")
    
    @abstractmethod
    def check_for_updates(self) -> list:
        """Return list of new items to process."""
        pass
    
    @abstractmethod
    def create_draft(self, item) -> Path:
        """Create draft file in /Pending_Approval/."""
        pass
    
    def claim_task(self, task_file: str) -> bool:
        """
        Claim a task by moving it to /In_Progress/cloud/
        Returns True if successfully claimed, False if already claimed.
        """
        source = NEEDS_ACTION / task_file
        dest = IN_PROGRESS / task_file
        
        if not source.exists():
            return False
        
        try:
            source.rename(dest)
            logger.info(f"Claimed task: {task_file}")
            return True
        except Exception as e:
            logger.warning(f"Failed to claim task {task_file}: {e}")
            return False
    
    def write_update(self, update_type: str, data: dict):
        """Write update to /Updates/ for Local agent."""
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        filename = f"{update_type}_{timestamp}.md"
        filepath = UPDATES / filename
        
        content = f"""---
type: {update_type}
timestamp: {datetime.now().isoformat()}
agent: cloud
---

# Cloud Agent Update

## Type: {update_type}

## Data
{json.dumps(data, indent=2)}

---
*Generated by cloud_watcher.py*
"""
        filepath.write_text(content, encoding="utf-8")
        logger.info(f"Update written: {filename}")
    
    def run(self):
        """Main watcher loop."""
        logger.info(f"Starting {self.__class__.__name__} (Cloud)")
        logger.info(f"Check interval: {self.check_interval}s")
        
        while True:
            try:
                items = self.check_for_updates()
                for item in items:
                    self.create_draft(item)
            except Exception as e:
                logger.error(f"Error in watcher: {e}")
            finally:
                self.save_state()
                time.sleep(self.check_interval)



def main():
    """Start all cloud watchers."""
    logger.info("=" * 60)
    logger.info("Cloud Watcher Starting (Platinum Tier)")
    logger.info(f"Vault root: {VAULT_ROOT}")
    logger.info("=" * 60)
    
    watchers = [
        GmailCloudWatcher(check_interval=300),  # 5 minutes
        SocialCloudWatcher(check_interval=600),  # 10 minutes
        AccountingCloudWatcher(check_interval=300),  # 5 minutes
    ]
    
    # Start all watchers
    for watcher in watchers:
        logger.info(f"Starting {watcher.__class__.__name__}")
    
    try:
        while True:
            for watcher in watchers:
                try:
                    items = watcher.check_for_updates()
                    for item in items:
                        watcher.create_draft(item)
                except Exception as e:
                    logger.error(f"Error in {watcher.__class__.__name__}: {e}")
                finally:
                    watcher.save_state()
            time.sleep(60)
    except KeyboardInterrupt:
        logger.info("Cloud Watcher stopped by user.")


if __name__ == "__main__":
    main()
